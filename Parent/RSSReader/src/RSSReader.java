import components.simplereader.SimpleReader;
import components.simplereader.SimpleReader1L;
import components.simplewriter.SimpleWriter;
import components.simplewriter.SimpleWriter1L;
import components.xmltree.XMLTree;
import components.xmltree.XMLTree1;

/**
 * Program to convert an XML RSS (version 2.0) feed from a given URL into the
 * corresponding HTML output file.
 *
 * @author Eve Mertic
 *
 */
public final class RSSReader {

    /**
     * Private constructor so this utility class cannot be instantiated.
     */
    private RSSReader() {
    }

    /**
     * Outputs the "opening" tags in the generated HTML file. These are the
     * expected elements generated by this method: <pre>
     *
     * <!DOCTYPE html>
     * <html lang="en">
     * <head>
     *  <title>the channel tag title as the page title</title>
     * </head>
     * <body>
     *  <h1>the page title inside a link to the <channel> link</h1>
     *  <p>
     *  the channel description
     *  </p>
     *  <table border="1">
     *   <tr>
     *    <th>Date</th>
     *    <th>Source</th>
     *    <th>News</th>
     *   </tr>
     *
     * </pre> Note: pre open & close tags are just for formatting this comment.
     * Method output should not include pre tags.
     *
     * @param channel
     *            the channel element XMLTree
     * @param out
     *            the output stream
     * @updates out.content
     * @requires [the root of channel is a <channel> tag] and out.is_open
     * @ensures out.content = #out.content * [the HTML "opening" tags]
     */
    private static void outputHeader(XMLTree channel, SimpleWriter out) {
        assert channel != null : "Violation of: channel is not null";
        assert out != null : "Violation of: out is not null";
        assert channel.isTag() && channel.label().equals("channel")
                : "" + "Violation of: the label root of channel is a <channel> tag";
        assert out.isOpen() : "Violation of: out.is_open";

        //Set title, link, and description
        String channelTitle = "Empty Title";
        String channelLink = "";
        String channelDescription = "No description";

        //Find the tags:
        int i = 0;
        while (i < channel.numberOfChildren()) {
            XMLTree child = channel.child(i);
            if (child.isTag()) {
                if (child.label().equals("title")) {
                    if (child.numberOfChildren() > 0) {
                        channelTitle = child.child(0).label();
                    }
                } else if (child.label().equals("link")) {
                    if (child.numberOfChildren() > 0) {
                        channelLink = child.child(0).label();
                    }
                } else if (child.label().equals("description")) {
                    if (child.numberOfChildren() > 0) {
                        channelDescription = child.child(0).label();
                    }
                }
            }
            i++;
        }
        //Print HTML heading:
        out.println("<html>");
        out.println("<head>");
        out.println("<title>" + channelTitle + "</title>");
        out.println("</head>");
        out.println("<h1><a href=\"" + channelLink + "\">" + channelTitle + "</a></h1>");
        out.println("<p>" + channelDescription + "</p>");
        out.println("<table border = \"1\">");
        out.println("<tr>");
        out.println("<th>Date</th>");
        out.println("<th>Source</th>");
        out.println("<th>News</th>");
        out.println("</tr>");
    }

    /**
     * Outputs the "closing" tags in the generated HTML file. These are the
     * expected elements generated by this method: <pre>
     *
     *  </table>
     * </body>
     * </html>
     *
     * </pre> Note: pre open & close tags are just for formatting this comment.
     * Method output should not include pre tags.
     *
     * @param out
     *            the output stream
     * @updates out.contents
     * @requires out.is_open
     * @ensures out.content = #out.content * [the HTML "closing" tags]
     */
    private static void outputFooter(SimpleWriter out) {
        assert out != null : "Violation of: out is not null";
        assert out.isOpen() : "Violation of: out.is_open";

        out.println("</table>");
        out.println("</body>");
        out.println("</html>");

    }

    /**
     * Finds the first occurrence of the given tag among the children of the
     * given {@code XMLTree} and return its index; returns -1 if not found.
     *
     * @param xml
     *            the {@code XMLTree} to search
     * @param tag
     *            the tag to look for
     * @return the index of the first child of type tag of the {@code XMLTree}
     *         or -1 if not found
     * @requires [the label of the root of xml is a tag]
     * @ensures <pre>
     * getChildElement =
     *  [the index of the first tag child of the {@code XMLTree} matching the
     *  given tag or -1 if not found]
     * </pre>
     */
    private static int getChildElement(XMLTree xml, String tag) {
        assert xml != null : "Violation of: xml is not null";
        assert tag != null : "Violation of: tag is not null";
        assert xml.isTag() : "Violation of: the label root of xml is a tag";

        int index = -1;
        int i = 0;
        while (i < xml.numberOfChildren() && index == -1) {
            if (xml.child(i).isTag() && xml.child(i).label().equals(tag)) {
                index = i;
            }
            i++;
        }
        return index;
    }

    /**
     * Processes one news item and outputs one table row. The row contains three
     * elements: the publication date, the source, and the title (or
     * description) of the item.
     *
     * @param item
     *            the news item
     * @param out
     *            the output stream
     * @updates out.content
     * @requires [the label of the root of item is an <item> tag] and
     *           out.is_open
     * @ensures <pre>
     * out.content = #out.content *
     *   [an HTML table row with publication date, source, and title of news item]
     * </pre>
     */
    private static void processItem(XMLTree item, SimpleWriter out) {
        assert item != null : "Violation of: item is not null";
        assert out != null : "Violation of: out is not null";
        assert item.isTag() && item.label().equals("item")
                : "" + "Violation of: the label root of item is an <item> tag";
        assert out.isOpen() : "Violation of: out.is_open";

        //Initialize default values
        String pubDate = "No date available";
        String source = "No source available";
        String sourceUrl = "";
        String title = "No title available";
        String link = "";

        //Publication Date:
        int pubDateIndex = getChildElement(item, "pubDate");
        if (pubDateIndex != -1) {
            XMLTree pubDateTag = item.child(pubDateIndex);
            if (pubDateTag.numberOfChildren() > 0) {
                pubDate = pubDateTag.child(0).label();
            }
        }

        //Find source:
        int sourceIndex = getChildElement(item, "source");
        if (sourceIndex != -1) {
            XMLTree sourceTag = item.child(sourceIndex);
            if (sourceTag.hasAttribute("url")) {
                sourceUrl = sourceTag.attributeValue("url");
            }
            if (sourceTag.numberOfChildren() > 0) {
                source = sourceTag.child(0).label();
            }
        }

        //Find title:
        int titleIndex = getChildElement(item, "title");
        if (titleIndex != -1) {
            XMLTree titleTag = item.child(titleIndex);
            if (titleTag.numberOfChildren() > 0) {
                title = titleTag.child(0).label();
            }
        }

        //Use description if no title:
        if (title.equals("No title available") || title.isEmpty()) {
            int descIndex = getChildElement(item, "description");
            if (descIndex != -1) {
                XMLTree descTag = item.child(descIndex);
                if (descTag.numberOfChildren() > 0) {
                    title = descTag.child(0).label();
                }
            }

        }

        //Find link:
        int linkIndex = getChildElement(item, "link");
        if (linkIndex != -1) {
            XMLTree linkTag = item.child(linkIndex);
            if (linkTag.numberOfChildren() > 0) {
                link = linkTag.child(0).label();
            }
        }

        //Print table rows:
        out.println("<tr>");
        out.println("<td>" + pubDate + "</td>");

        //Print link source:
        if (!sourceUrl.isEmpty()) {
            out.println("<td><a href=\"" + sourceUrl + "\">" + source + "</a></td>");
        } else {
            out.println("<td>" + source + "</td>");
        }

        //Output title and link
        if (!link.isEmpty()) {
            out.println("<td><a href=\"" + link + "\">" + title + "</a></td>");
        } else {
            out.println("<td>" + title + "</td>");
        }

        out.println("</tr>");
    }

    /**
     * Main method.
     *
     * @param args
     *            the command line arguments; unused here
     */
    public static void main(String[] args) {
        SimpleReader in = new SimpleReader1L();
        SimpleWriter out = new SimpleWriter1L();

        //User prompts:
        out.print("Enter the URL of an RSS 2.0 feed: ");
        String url = in.nextLine();

        out.print("Enter the name of the output file (with .html): ");
        String outputFile = in.nextLine();

        XMLTree rss = new XMLTree1(url);

        //Check if the root is <rss> tag version 2.0
        if (!rss.isTag() || !rss.label().equals("rss")) {
            out.println("Error: the document root is not an <rss> tag.");
        } else if (!rss.hasAttribute("version")
                || !rss.attributeValue("version").equals("2.0")) {
            out.println("Error: RSS vedrsion is not 2.0.");
        } else {
            int channelIndex = getChildElement(rss, "channel");
            if (channelIndex != -1) {
                XMLTree channel = rss.child(channelIndex);

                //Create output file:
                SimpleWriter fileOut = new SimpleWriter1L(outputFile);

                outputHeader(channel, fileOut);

                //Process all items
                int i = 0;
                while (i < channel.numberOfChildren()) {
                    XMLTree child = channel.child(i);
                    if (child.isTag() && child.label().equals("item")) {
                        processItem(child, fileOut);
                    }
                    i++;
                }

                outputFooter(fileOut);

                fileOut.close();

                out.println("HTML file created: " + outputFile);
            } else {
                out.println("Error: no <channel> tag found in RSS feed.");
            }
        }

        in.close();
        out.close();
    }

}
